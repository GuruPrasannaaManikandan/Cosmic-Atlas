import { describe, it, expect } from 'vitest'
import {
  ASSET_REGISTRY,
  loadScientificTexture,
  getEarthTexture,
  getEarthCloudsTexture,
  getEarthSpecularTexture,
  getMoonTexture,
  getMarsTexture,
  getJupiterTexture,
  getSaturnTexture,
  getSaturnRingsTexture,
  getSunPhotosphereTexture,
  getBetelgeuseTexture,
  getAndromedaTexture,
  getCarinaTexture,
} from './assetRegistry'

describe('Astronomical Asset Registry & Scientific Provenance', () => {
  it('records truthful provenance for every asset (no third-party or procedural file labelled as a NASA original)', () => {
    for (const a of Object.values(ASSET_REGISTRY)) {
      expect(a.provenanceClass, a.id).toBeDefined()
      expect(a.attribution.length, a.id).toBeGreaterThan(0)
      expect(a.sourceUrl.length, a.id).toBeGreaterThan(0)
      expect(a.projection.length, a.id).toBeGreaterThan(0)
      // procedural / unverified files must never claim an observatory as their source or public-domain status
      if (a.provenanceClass === 'procedural' || a.provenanceClass === 'unverified') {
        expect(a.license, a.id).not.toMatch(/public domain/i)
        expect(a.source, a.id).not.toMatch(/^(NASA|ESA|ESO|Hubble|JPL)/)
      }
      // CC BY requires a visible credit line naming the author and the licence
      if (/CC BY/.test(a.license)) expect(a.attribution, a.id).toMatch(/CC BY/)
    }
    // the planet maps fetched by download_authentic_textures.py are Solar System Scope CC BY 4.0 derivatives of NASA data
    for (const id of ['earth_day', 'earth_clouds', 'earth_night', 'mars_albedo', 'jupiter_color', 'saturn_color', 'saturn_rings', 'moon_albedo', 'sun_photosphere']) {
      expect(ASSET_REGISTRY[id].license, id).toBe('CC BY 4.0')
      expect(ASSET_REGISTRY[id].source, id).toMatch(/Solar System Scope/)
    }
    // generated by scripts/build_astronomical_assets.py
    for (const id of ['betelgeuse_surface', 'andromeda_m31', 'carina_nebula']) expect(ASSET_REGISTRY[id].provenanceClass, id).toBe('procedural')
    for (const id of ['earth_specular', 'earth_normal']) expect(ASSET_REGISTRY[id].licenseVerified, id).toBe(false)
  })

  it('registers all key celestial targets with a source, licence and usable dimensions', () => {
    const requiredAssets = [
      'earth_day',
      'earth_clouds',
      'earth_specular',
      'moon_albedo',
      'mars_albedo',
      'jupiter_color',
      'saturn_color',
      'saturn_rings',
      'sun_photosphere',
      'betelgeuse_surface',
      'andromeda_m31',
      'carina_nebula',
    ]

    for (const key of requiredAssets) {
      const asset = ASSET_REGISTRY[key]
      expect(asset).toBeDefined()
      expect(asset.id).toBe(key)
      expect(asset.path).toMatch(/^\/assets\/astronomy\/textures\//)
      expect(asset.source).toBeDefined()
      expect(asset.license.length).toBeGreaterThan(0)
      expect(asset.dimensions[0]).toBeGreaterThanOrEqual(1024)
      expect(asset.dimensions[1]).toBeGreaterThanOrEqual(64)
    }
  })

  it('specifies sRGB color space for color maps and Linear for specular masks', () => {
    expect(ASSET_REGISTRY.earth_day.colorSpace).toBe('sRGB')
    expect(ASSET_REGISTRY.earth_specular.colorSpace).toBe('Linear')
    expect(ASSET_REGISTRY.saturn_rings.colorSpace).toBe('sRGB')
  })

  it('safely falls back to procedural textures in non-browser/SSR environments', () => {
    const earthTex = getEarthTexture()
    expect(earthTex).toBeDefined()

    const cloudsTex = getEarthCloudsTexture()
    expect(cloudsTex).toBeDefined()

    const specularTex = getEarthSpecularTexture()
    expect(specularTex).toBeDefined()

    const moonTex = getMoonTexture()
    expect(moonTex).toBeDefined()

    const marsTex = getMarsTexture()
    expect(marsTex).toBeDefined()

    const jupiterTex = getJupiterTexture()
    expect(jupiterTex).toBeDefined()

    const saturnTex = getSaturnTexture()
    expect(saturnTex).toBeDefined()

    const ringsTex = getSaturnRingsTexture()
    expect(ringsTex).toBeDefined()

    const sunTex = getSunPhotosphereTexture()
    expect(sunTex).toBeDefined()

    const betelgeuseTex = getBetelgeuseTexture()
    expect(betelgeuseTex).toBeDefined()

    const andromedaTex = getAndromedaTexture()
    expect(andromedaTex).toBeDefined()

    const carinaTex = getCarinaTexture()
    expect(carinaTex).toBeDefined()
  })

  it('handles unknown asset identifiers with safe fallback', () => {
    const unknownTex = loadScientificTexture('non_existent_quasar_surface')
    expect(unknownTex).toBeDefined()
  })
})
