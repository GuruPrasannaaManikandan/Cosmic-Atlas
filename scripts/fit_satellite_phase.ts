/**
 * Phase refinement of the JPL SSD satellite mean elements (see docs/ORBITAL_MECHANICS.md).
 *
 * For every moon, each Horizons sample (scripts/data/horizons_satellite_samples.json) is rotated into the moon's
 * PUBLISHED orbital plane at that instant (JPL Ω(t), i, ω(t), reference plane), its true anomaly is converted to a
 * mean anomaly with the published e, and the residual against the published mean anomaly is unwrapped in time.
 * A straight line M_obs - M_pub = c0 + c1·(t - epoch) is fitted by least squares: c0 corrects the mean anomaly at
 * epoch, c1 the mean motion. Nothing else is changed. The fit also reports the in-plane and out-of-plane RMS.
 *
 * Run from frontend/:  npx vite-node ../scripts/fit_satellite_phase.ts
 * Writes frontend/src/data/satellitePhaseFit.ts
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { SOLAR_BODY_BY_ID } from '../frontend/src/data/solarSystem'
import { anglesAt, frameToGalactic, KeplerElements } from '../frontend/src/astro/kepler'
import { equatorialToGalactic, mulMat, Vec3 } from '../frontend/src/astro/coords'
import { jdTdbFromUtcMs, JD_UNIX_EPOCH, MS_PER_DAY } from '../frontend/src/astro/time'

const R2D = 180 / Math.PI
const root = resolve(__dirname, '..')
const samples = JSON.parse(readFileSync(resolve(root, 'scripts/data/horizons_satellite_samples.json'), 'utf8'))

const wrap180 = (x: number) => ((x + 180) % 360 + 360) % 360 - 180

function planeAngles(el: KeplerElements, jd: number, g: Vec3): { M: number; z: number } {
  const a = anglesAt(el, jd)
  const F = frameToGalactic(el.frame)
  const Ft = [0, 1, 2].map((r) => [0, 1, 2].map((c) => F[c][r]))
  const ref = mulMat(Ft, g)
  // undo Rz(Ω)·Rx(i)·Rz(ω)
  const rz = (v: Vec3, t: number): Vec3 => [Math.cos(t) * v[0] - Math.sin(t) * v[1], Math.sin(t) * v[0] + Math.cos(t) * v[1], v[2]]
  const rx = (v: Vec3, t: number): Vec3 => [v[0], Math.cos(t) * v[1] - Math.sin(t) * v[2], Math.sin(t) * v[1] + Math.cos(t) * v[2]]
  const p = rz(rx(rz(ref, -a.node), -a.i), -a.argp)
  const nu = Math.atan2(p[1], p[0])
  const e = el.e
  const E = 2 * Math.atan2(Math.sqrt(1 - e) * Math.sin(nu / 2), Math.sqrt(1 + e) * Math.cos(nu / 2))
  const M = (E - e * Math.sin(E)) * R2D
  const z = Math.atan2(p[2], Math.hypot(p[0], p[1])) * R2D
  return { M, z }
}

const out: Record<string, object> = {}
const report: string[] = []
for (const [id, body] of Object.entries<any>(samples.bodies)) {
  const b = SOLAR_BODY_BY_ID[id]
  if (!b?.orbit.rawElements) throw new Error(`no raw elements for ${id}`)
  const el = b.orbit.rawElements
  const xs: number[] = [], ys: number[] = [], zs: number[] = []
  let prev: number | null = null, unwrap = 0
  for (const [jdUt, x, y, z] of body.jd_ut_xyz_km as number[][]) {
    const ms = (jdUt - JD_UNIX_EPOCH) * MS_PER_DAY
    const jd = jdTdbFromUtcMs(ms)
    const g = equatorialToGalactic([x, y, z])
    const { M, z: lat } = planeAngles(el, jd, g)
    const Mpub = el.meanAnomalyDeg + el.meanMotionDegPerDay * (jd - el.epochJd)
    let r = wrap180(M - Mpub)
    if (prev !== null) {
      while (r + unwrap - prev > 180) unwrap -= 360
      while (r + unwrap - prev < -180) unwrap += 360
    }
    r += unwrap
    prev = r
    xs.push(jd - el.epochJd); ys.push(r); zs.push(lat)
  }
  const n = xs.length
  const mx = xs.reduce((s, v) => s + v, 0) / n, my = ys.reduce((s, v) => s + v, 0) / n
  let sxy = 0, sxx = 0
  for (let k = 0; k < n; k++) { sxy += (xs[k] - mx) * (ys[k] - my); sxx += (xs[k] - mx) ** 2 }
  const c1 = sxy / sxx, c0raw = my - c1 * mx
  const c0 = wrap180(c0raw) // adding whole turns to M changes nothing
  const rms = Math.sqrt(ys.reduce((s, v, k) => s + (v - (c0raw + c1 * xs[k])) ** 2, 0) / n)
  const rmsZ = Math.sqrt(zs.reduce((s, v) => s + v * v, 0) / n)
  out[id] = { dM0Deg: +c0.toFixed(6), dMdotDegPerDay: +c1.toExponential(9), window: `${samples.start}..${samples.stop} step ${samples.step}`, samples: n, rmsAlongDeg: +rms.toFixed(4), rmsOutOfPlaneDeg: +rmsZ.toFixed(4) }
  report.push(`${id.padEnd(11)} dM0=${c0.toFixed(3).padStart(10)}°  dMdot=${c1.toExponential(3).padStart(11)}°/d  rms_along=${rms.toFixed(3).padStart(7)}°  rms_out=${rmsZ.toFixed(3).padStart(6)}°`)
}

const file = `// GENERATED by scripts/fit_satellite_phase.ts - do not edit by hand.
// Source samples: ${samples.source}, ${samples.frame}, ${samples.start}..${samples.stop} step ${samples.step}, retrieved ${samples.retrieved}.
export interface PhaseFit {
  dM0Deg: number
  dMdotDegPerDay: number
  window: string
  samples: number
  rmsAlongDeg: number
  rmsOutOfPlaneDeg: number
}

export const SATELLITE_PHASE_FIT: Record<string, PhaseFit> = ${JSON.stringify(out, null, 2)}
`
writeFileSync(resolve(root, 'frontend/src/data/satellitePhaseFit.ts'), file)
console.log(report.join('\n'))

